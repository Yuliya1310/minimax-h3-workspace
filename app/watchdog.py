"""Вердикт по заданию, которое ComfyUI держит в очереди, но ничего о нём не сообщает.

Длинный клип MiniMax H3 молчит по-честному: 243 кадра при 864x480 на карте с 24 ГБ тратят около
двадцати минут на один шаг генерации, а приложение считало это зависанием уже через десять минут
и советовало перезапустить ComfyUI — то есть выбросило бы работающий рендер. Поэтому теперь
тишина даёт только уведомление, а задание снимается лишь тогда, когда молчит часами *и* карта
ничего не делает.
"""

QUIET_NOTICE = 600      # десять минут без событий: сообщить, что работа идёт
QUIET_GIVE_UP = 7200    # два часа тишины при простаивающей карте: вот это уже зависание


def job_verdict(in_queue, silent, gpu_busy, notice_after=QUIET_NOTICE, give_up_after=QUIET_GIVE_UP):
    """'ok' | 'notice' | 'stale' для задания, которое ComfyUI ещё держит.

    `gpu_busy` — True/False, когда карту удалось прочитать, и None, когда неизвестно;
    неизвестная карта никогда не валит задание, это делает только простаивающая после часов тишины.
    """
    if not in_queue:
        return "stale"                      # у ComfyUI его нет вовсе
    if silent < notice_after:
        return "ok"
    if silent < give_up_after or gpu_busy is not False:
        return "notice"
    return "stale"
